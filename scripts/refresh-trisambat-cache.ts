// scripts/refresh-trisambat-cache.ts
//
// Dedicated cache refresh script for Trisambat API holiday data.
//
// Usage: npx tsx scripts/refresh-trisambat-cache.ts
//
// Fetches holiday data for BS years 2082, 2083, 2084 (the only years with
// verified holiday data in the API) and writes:
//   - cache/trisambat/holidays-{bsYear}.json   (raw API response)
//   - cache/trisambat/meta-{bsYear}.json       (retrievedAt, sourceUrl, etag, provisional)
//   - cache/trisambat/cached-data.ts           (TypeScript module for website)
//
// Rules:
//   - Never fails the build if the API is unavailable
//   - Preserves the last successfully fetched cache on refresh failure
//   - Records retrievedAt and ETag metadata
//   - Only fetches 2082, 2083, 2084 (2085 not covered by API)
//   - Does not run during normal website visits or npm run build

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import {
  fetchTrisambatHolidays,
  trisambatHolidaysUrl,
} from '../lib/trisambat-cache';

const CACHE_DIR = join(process.cwd(), 'cache', 'trisambat');
const YEARS_TO_FETCH = [2082, 2083, 2084];

interface FetchResult {
  year: number;
  data: unknown;
  meta: unknown;
  success: boolean;
  error?: string;
}

/** Generate the TypeScript module content for cached-data.ts. */
function generateCacheModule(entries: Record<number, { data: unknown; meta: unknown }>): string {
  const lines = [
    '// cache/trisambat/cached-data.ts',
    '//',
    '// Auto-generated by scripts/refresh-trisambat-cache.ts.',
    '// Do not edit manually — this file is overwritten on each refresh.',
    '//',
    '// Before the first refresh, this exports an empty cache.',
    '// After refresh, it contains Trisambat API holiday data for cached BS years.',
    '',
    "export const TRISAMBAT_CACHE: Record<number, { data: unknown; meta: unknown }> = {",
  ];

  const years = Object.keys(entries)
    .map(Number)
    .sort((a, b) => a - b);

  for (const year of years) {
    const entry = entries[year];
    const dataJson = JSON.stringify(entry.data, null, 2);
    const metaJson = JSON.stringify(entry.meta, null, 2);
    lines.push(`  ${year}: {`);
    lines.push(`    data: ${dataJson},`);
    lines.push(`    meta: ${metaJson},`);
    lines.push(`  },`);
  }

  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

async function main(): Promise<void> {
  console.log('Trisambat cache refresh starting...');
  console.log(`Target years: ${YEARS_TO_FETCH.join(', ')}`);

  // Ensure cache directory exists
  if (!existsSync(CACHE_DIR)) {
    mkdirSync(CACHE_DIR, { recursive: true });
  }

  const entries: Record<number, { data: unknown; meta: unknown }> = {};

  // Try to load existing cache data first (preserve on failure)
  for (const year of YEARS_TO_FETCH) {
    try {
      const dataPath = join(CACHE_DIR, `holidays-${year}.json`);
      const metaPath = join(CACHE_DIR, `meta-${year}.json`);
      if (existsSync(dataPath) && existsSync(metaPath)) {
        const data = JSON.parse(readFileSync(dataPath, 'utf8'));
        const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
        entries[year] = { data, meta };
        console.log(`  ${year}: loaded existing cache (${data.events?.length ?? 0} events)`);
      }
    } catch {
      // Ignore read errors for existing cache
    }
  }

  let successCount = 0;
  let failCount = 0;

  for (const year of YEARS_TO_FETCH) {
    const url = trisambatHolidaysUrl(year);
    console.log(`Fetching ${url}...`);

    try {
      const result = await fetchTrisambatHolidays(year);
      if (result) {
        // Write raw JSON files for reference/audit
        const dataPath = join(CACHE_DIR, `holidays-${year}.json`);
        const metaPath = join(CACHE_DIR, `meta-${year}.json`);
        try {
          writeFileSync(dataPath, JSON.stringify(result.data, null, 2), 'utf8');
          writeFileSync(metaPath, JSON.stringify(result.meta, null, 2), 'utf8');
        } catch (writeErr) {
          console.log(`  ✗ ${year}: failed to write cache files: ${writeErr}`);
          failCount++;
          continue;
        }

        entries[year] = { data: result.data, meta: result.meta };
        console.log(
          `  ✓ ${year}: ${result.data.events.length} events, ` +
            `retrievedAt=${result.meta.retrievedAt}, ` +
            `etag=${result.meta.etag ?? 'none'}, ` +
            `provisional=${result.meta.provisional ?? false}`,
        );
        successCount++;
      } else {
        console.log(`  ✗ ${year}: API fetch failed (network or invalid response)`);
        // Preserve existing cache if present — do not discard
        failCount++;
      }
    } catch (err) {
      console.log(`  ✗ ${year}: unexpected error: ${err}`);
      failCount++;
    }
  }

  // Regenerate cached-data.ts from all collected entries (existing + new)
  try {
    const moduleContent = generateCacheModule(entries);
    writeFileSync(join(CACHE_DIR, 'cached-data.ts'), moduleContent, 'utf8');
    console.log(
      `\nGenerated cache/trisambat/cached-data.ts with ${Object.keys(entries).length} years`,
    );
  } catch (err) {
    console.log(`\n⚠ Failed to generate cached-data.ts: ${err}`);
  }

  console.log(
    `\nRefresh complete: ${successCount} succeeded, ${failCount} failed.`,
  );
  console.log(
    'Existing cache files are preserved. Old cache is never discarded on failure.',
  );
}

main().catch((err) => {
  console.error('Refresh script failed unexpectedly:', err);
  process.exit(1);
});
